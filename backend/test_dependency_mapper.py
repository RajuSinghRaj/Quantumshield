def test_source_to_dependency_mapping_and_active_detection():
    """Verify correlation between manifest dependencies and source-code findings."""
    files_data = [
        {
            "rel_path": "requirements.txt",
            "content": "cryptography>=41.0.0\npycryptodome==3.18.0\nrequests>=2.28.0\n"
        },
        {
            "rel_path": "src/crypto_utils.py",
            "content": "from cryptography.hazmat.primitives.asymmetric import rsa\nrsa.generate_private_key(public_exponent=65537, key_size=2048)"
        }
    ]

    scanner_findings = [
        {
            "algorithm": "RSA",
            "variant": "RSA-2048",
            "key_size": 2048,
            "library_or_api": "cryptography.hazmat.primitives.asymmetric.rsa",
            "file_path": "src/crypto_utils.py",
            "line_number": 2,
            "quantum_risk": "VULNERABLE",
            "classical_risk": "SAFE"
        }
    ]

    analysis = CryptographicDependencyMapper.analyze_cryptographic_dependencies(
        files_data=files_data,
        scanner_findings=scanner_findings
    )

    deps = {d["package_name"]: d for d in analysis["dependencies"]}

    # Non-crypto library 'requests' was filtered out
    assert "requests" not in deps

    # 'cryptography' is actively referenced in source code
    assert "cryptography" in deps
    assert deps["cryptography"]["active_in_code"] is True
    assert "RSA" in deps["cryptography"]["associated_algorithms"]
    assert "src/crypto_utils.py" in deps["cryptography"]["related_files"]
    assert deps["cryptography"]["quantum_risk"] == "VULNERABLE"

    # 'pycryptodome' is declared in manifest but not referenced in findings -> declared only
    assert "pycryptodome" in deps
    assert deps["pycryptodome"]["active_in_code"] is False
    assert len(deps["pycryptodome"]["associated_algorithms"]) == 0


def test_dependency_relationship_graph_integrity():
    """Verify graph topological integrity: Project -> Package -> Algorithm -> Finding."""
    files_data = [
        {
            "rel_path": "package.json",
            "content": '{"dependencies": {"crypto-js": "4.2.0"}}'
        }
    ]
    scanner_findings = [
        {
            "algorithm": "AES",
            "variant": "AES-256-GCM",
            "library_or_api": "cryptojs",
            "file_path": "src/encrypt.js",
            "line_number": 14,
            "quantum_risk": "SAFE",
            "classical_risk": "SAFE"
        }
    ]

    analysis = CryptographicDependencyMapper.analyze_cryptographic_dependencies(
        files_data=files_data,
        scanner_findings=scanner_findings
    )

    graph = analysis["dependency_graph"]
    nodes = {n["id"]: n for n in graph["nodes"]}
    links = graph["links"]

    # Check root project node
    assert "project:root" in nodes

    # Check package node
    pkg_id = "pkg:npm:crypto-js"
    assert pkg_id in nodes
    assert nodes[pkg_id]["type"] == "package"

    # Check algorithm node
    algo_id = "algo:npm:crypto-js:AES"
    assert algo_id in nodes
    assert nodes[algo_id]["type"] == "algorithm"

    # Check finding node
    finding_id = "finding:src/encrypt.js:14:AES"
    assert finding_id in nodes
    assert nodes[finding_id]["type"] == "finding"

    # Check links: project -> pkg -> algo -> finding
    link_pairs = {(l["source"], l["target"]) for l in links}
    assert ("project:root", pkg_id) in link_pairs
    assert (pkg_id, algo_id) in link_pairs
    assert (algo_id, finding_id) in link_pairs


def test_migration_impact_analysis_generation():
    """Verify migration impact correctly assesses complexity for vulnerable and safe libraries."""
    files_data = [
        {
            "rel_path": "requirements.txt",
            "content": "pycryptodome==3.18.0\n"
        }
    ]
    scanner_findings = [
        {
            "algorithm": "RSA",
            "variant": "RSA-2048",
            "library_or_api": "pycryptodome",
            "file_path": "app/auth.py",
            "line_number": 10,
            "quantum_risk": "VULNERABLE",
            "classical_risk": "SAFE"
        }
    ]

    analysis = CryptographicDependencyMapper.analyze_cryptographic_dependencies(
        files_data=files_data,
        scanner_findings=scanner_findings
    )

    impacts = analysis["migration_impact"]
    assert len(impacts) == 1
    pcd_impact = impacts[0]

    assert pcd_impact["package_name"] == "pycryptodome"
    assert pcd_impact["migration_complexity"] == "HIGH"
    assert "does not support NIST PQC" in pcd_impact["complexity_reason"]
    assert pcd_impact["affected_files_count"] == 1


