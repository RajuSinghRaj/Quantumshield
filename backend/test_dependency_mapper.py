def test_package_json_and_lockfile_direct_vs_transitive():
    """Verify package.json and package-lock.json with direct vs transitive classification."""
    pkg_json = """
    {
      "name": "crypto-frontend",
      "dependencies": {
        "crypto-js": "^4.2.0",
        "react": "^18.2.0"
      },
      "devDependencies": {
        "@noble/curves": "^1.3.0"
      }
    }
    """
    direct_deps = ManifestParser.parse_package_json(pkg_json, "package.json")
    direct_names = {d["name"] for d in direct_deps}
    assert "crypto-js" in direct_names
    assert "@noble/curves" in direct_names
    assert "react" in direct_names

    # Lockfile contains both direct and transitive dependencies
    lock_json = """
    {
      "name": "crypto-frontend",
      "version": "1.0.0",
      "lockfileVersion": 3,
      "packages": {
        "node_modules/crypto-js": {
          "version": "4.2.0"
        },
        "node_modules/@noble/curves": {
          "version": "1.3.0"
        },
        "node_modules/tweetnacl": {
          "version": "1.0.3"
        }
      }
    }
    """
    lock_deps = ManifestParser.parse_package_lock_json(lock_json, "package-lock.json", direct_names)
    dep_map = {d["name"]: d for d in lock_deps}

    assert dep_map["crypto-js"]["direct"] is True
    assert dep_map["crypto-js"]["transitive"] is False
    assert dep_map["@noble/curves"]["direct"] is True

    # tweetnacl was not in package.json -> must be marked transitive!
    assert "tweetnacl" in dep_map
    assert dep_map["tweetnacl"]["direct"] is False
    assert dep_map["tweetnacl"]["transitive"] is True


